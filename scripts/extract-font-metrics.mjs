/**
 * Bakes the AFM metrics for the PDF standard fonts into a small JSON file so
 * the runtime PDF generator can measure and wrap text without shipping a font
 * library. The standard 14 fonts need no embedding, which keeps generated CVs
 * around 5 KB each.
 *
 * Run with: npm run gen:metrics
 */
import { writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { Font, FontNames, Encodings } = require('@pdf-lib/standard-fonts');

const FACES = {
  regular: FontNames.Helvetica,
  bold: FontNames.HelveticaBold,
  italic: FontNames.HelveticaOblique,
  boldItalic: FontNames.HelveticaBoldOblique
};

/** Unicode code point -> WinAnsi byte. Anything absent renders as '?'. */
const encoding = {};
for (const [codePoint, [byte]] of Object.entries(Encodings.WinAnsi.unicodeMappings)) {
  encoding[codePoint] = byte;
}

const fonts = {};
for (const [key, name] of Object.entries(FACES)) {
  const font = Font.load(name);
  const byName = new Map(font.CharMetrics.map((m) => [m.N, m.WX]));
  const widths = new Array(256).fill(0);
  for (const [, [byte, glyph]] of Object.entries(Encodings.WinAnsi.unicodeMappings)) {
    if (byName.has(glyph)) widths[byte] = byName.get(glyph);
  }
  fonts[key] = {
    baseFont: name,
    ascender: font.Ascender,
    descender: font.Descender,
    capHeight: font.CapHeight,
    xHeight: font.XHeight,
    widths
  };
}

const out = { unitsPerEm: 1000, fallbackByte: 63, encoding, fonts };
const target = new URL('../src/lib/fonts/helvetica-metrics.js', import.meta.url);
await writeFile(
  target,
  '// Generated by scripts/extract-font-metrics.mjs — do not edit by hand.\n' +
    'export default ' + JSON.stringify(out) + ';\n',
  'utf8'
);

const bytes = JSON.stringify(out).length;
console.log(
  `wrote helvetica-metrics.js — ${Object.keys(fonts).length} faces, ` +
    `${Object.keys(encoding).length} encodable code points, ${(bytes / 1024).toFixed(1)} KB`
);
